#pragma once

#include <cstdint>

// **설정을 한 곳에.** 바꿔가며 시험하는 값들이다.
//
// 한때 이 값들이 세 군데 흩어져 있었다 (헤더의 상수 둘, 스왑체인 생성 코드의 하드코딩
// 하나). 어느 것을 바꿀 수 있는지 알려면 코드를 뒤져야 했다.
//
// **컴파일 상수인 이유**: 지금 목적은 구조를 이해하는 것이지 실험을 자주 돌리는 게
// 아니다. 스윕을 자주 하게 되면 그때 argv로 받는다 - 그러면 Frame 배열이
// 최대치 상수 + 런타임 개수로 바뀐다.

// **CPU가 GPU보다 몇 프레임 앞서갈 수 있나.**
//
// 1이면 매 프레임 CPU가 GPU를 기다린다. 2면 GPU가 N번을 그리는 동안 CPU가 N+1번을
// 준비한다. 늘리면 그만큼 자원이 배로 든다(커맨드 버퍼 · acquire 세마포어 · 펜스).
// 3 이상은 지연이 늘어나는 대신 얻는 게 적어서 잘 안 쓴다.
//
// 실측(120Hz, 삼각형 하나): 1이든 2든 차이가 없었다. 프레임 시간의 90%가
// acquire(모니터 대기)라 CPU가 GPU를 기다리는 상황이 아니었기 때문이다.
// **GPU가 바빠져야 의미가 생긴다.**
constexpr uint32_t kFramesInFlight = 2;

// **스왑체인 이미지를 몇 장 요청할까.** frames-in-flight와 다른 축이다:
//   frames-in-flight  CPU가 몇 프레임 앞서나  (펜스가 막는다)
//   이미지 개수        엔진이 몇 장을 돌리나    (acquire가 막는다)
//
// 요청값일 뿐이다 - caps.minImageCount 아래로는 못 가고 드라이버가 더 줄 수도 있다.
//
// 3인 근거는 우리 측정이 아니라 Khronos 샘플이다
// (Vulkan-Samples/performance/swapchain_images): GPU가 바쁠 때 2장이면 vsync를
// 놓쳐 60->30으로 반토막나고, 3장이면 "항상 처리된 이미지가 준비돼 있어" 안 멈춘다.
// 우리는 부하가 없어서 그 차이가 아직 안 보인다.
constexpr uint32_t kDesiredSwapchainImages = 3;

// **우리 이미지에 그리는 해상도.** 창 크기와 아무 관계가 없다.
//
// Vulkan에서 서피스와 스왑체인은 **선택적 확장**이다 - 창 없이도 렌더링이 완전히
// 성립한다. 그래서 방향이 이렇다: 우리 타겟에 다 그린 다음, 그 결과를 스왑체인으로
// **내보낸다**. 내보내기는 표시 단계이지 렌더링 단계가 아니다.
//
// 창과 다른 값으로 놓고 리사이즈해보면 그 독립성이 눈에 보인다 - 창을 늘려도
// 렌더 해상도는 그대로고 두 번째 패스의 샘플러가 늘려준다.
//
// **고정인 이유**: 창을 따라가게 하면 리사이즈마다 프레임 타겟을 다시 만드는 경로가
// 하나 더 생긴다. 지금은 그럴 근거가 없다.
// **동적으로 바꿀 때**: 확대가 화질 문제를 만들거나, 부하에 따라 해상도를
// 낮추고 싶어질 때. 그때 이 값이 런타임 변수가 되고 재생성 경로가 생긴다.
constexpr uint32_t kRenderWidth = 1280;
constexpr uint32_t kRenderHeight = 720;
